// Lay out text as panel-pixel cells. Returns { width, height, cells: [[x, y]] } with 1 pixel between letters
// and 1 row between lines.
export function layoutText(text, font) {
  const lines = String(text).toUpperCase().split('\n');
  const cells = [];
  let width = 0;
  lines.forEach((line, row) => {
    let x = 0;
    for (const ch of line) {
      const g = font[ch] || font['?'];
      g.forEach((r, y) => [...r].forEach((c, gx) => { if (c === '#') cells.push([x + gx, row * 6 + y]); }));
      x += 4;
    }
    width = Math.max(width, x - 1);
  });
  return { width: Math.max(0, width), height: lines.length * 6 - 1, cells };
}
